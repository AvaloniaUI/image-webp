#!/usr/bin/env python3
"""Generates src/lossy/vp8enc/tables.rs from libwebp's C sources.

Usage: extract_libwebp_tables.py <libwebp>/src > src/lossy/vp8enc/tables.rs
"""
import re
import sys

TABLES = [
    # (file, C name, rust name, rust element type, dims)
    ("enc/quant_enc.c", "kDcTable", "DC_TABLE", "u8", [128]),
    ("enc/quant_enc.c", "kAcTable", "AC_TABLE", "u16", [128]),
    ("enc/quant_enc.c", "kAcTable2", "AC_TABLE2", "u16", [128]),
    ("enc/cost_enc.c", "VP8LevelCodes", "LEVEL_CODES", "u16", [67, 2]),
    ("enc/cost_enc.c", "VP8FixedCostsI4", "FIXED_COSTS_I4", "u16", [10, 10, 10]),
    ("dsp/cost.c", "VP8EntropyCost", "ENTROPY_COST", "u16", [256]),
    ("dsp/cost.c", "VP8LevelFixedCosts", "LEVEL_FIXED_COSTS", "u16", [2048]),
    ("dsp/cost.c", "VP8EncBands", "ENC_BANDS", "u8", [17]),
    ("enc/tree_enc.c", "VP8CoeffsProba0", "COEFFS_PROBA0", "u8", [4, 8, 3, 11]),
    ("enc/tree_enc.c", "VP8CoeffsUpdateProba", "COEFFS_UPDATE_PROBA", "u8", [4, 8, 3, 11]),
    ("enc/tree_enc.c", "kBModesProba", "BMODES_PROBA", "u8", [10, 10, 9]),
    ("enc/filter_enc.c", "kLevelsFromDelta", "LEVELS_FROM_DELTA", "u8", [8, 64]),
    ("enc/picture_csp_enc.c", "kInvAlpha", "INV_ALPHA", "u32", [4 * 255 + 1]),
    ("utils/bit_writer_utils.c", "kNorm", "NORM", "u8", [128]),
    ("utils/bit_writer_utils.c", "kNewRange", "NEW_RANGE", "u8", [128]),
]


def strip_comments(src):
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    return re.sub(r"//[^\n]*", "", src)


def extract(src, name):
    m = re.search(r"\b" + re.escape(name) + r"\s*(\[[^=]*\])\s*=\s*\{", src)
    if not m:
        raise SystemExit(f"table {name} not found")
    i, depth = m.end(), 1
    while depth:
        c = src[i]
        depth += c == "{"
        depth -= c == "}"
        i += 1
    body = src[m.end():i - 1]
    return [int(v, 0) for v in re.findall(r"0x[0-9a-fA-F]+|\d+", body)]


def rust_type(elem, dims):
    t = elem
    for d in reversed(dims):
        t = f"[{t}; {d}]"
    return t


def nest(values, dims):
    if len(dims) == 1:
        return "[" + ", ".join(map(str, values)) + "]"
    step = len(values) // dims[0]
    inner = [nest(values[k * step:(k + 1) * step], dims[1:]) for k in range(dims[0])]
    return "[\n" + ",\n".join(inner) + ",\n]"


def main():
    root = sys.argv[1]
    print("// Generated by scripts/extract_libwebp_tables.py from libwebp 1.6.0. Do not edit.")
    print("// libwebp is Copyright Google Inc., BSD-3-Clause; see src/lossy/vp8enc/mod.rs.")
    print("#![cfg_attr(rustfmt, rustfmt_skip)]")
    print()
    cache = {}
    for file, cname, rname, elem, dims in TABLES:
        if file not in cache:
            with open(f"{root}/{file}") as f:
                cache[file] = strip_comments(f.read())
        values = extract(cache[file], cname)
        total = 1
        for d in dims:
            total *= d
        if len(values) != total:
            raise SystemExit(f"{cname}: expected {total} values, got {len(values)}")
        print(f"pub(crate) static {rname}: {rust_type(elem, dims)} = {nest(values, dims)};")
        print()


main()
